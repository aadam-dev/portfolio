// Write the back office schema (src/db/sql.ts) to the Supabase migration, so
// the Supabase GitHub integration applies the same SQL the app runs on start.
//
//   node scripts/db-sql.mjs          write the migration
//   node scripts/db-sql.mjs --check  fail if it is out of date
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";

const src = readFileSync(new URL("../src/db/sql.ts", import.meta.url), "utf8");
const m = src.match(/SCHEMA_SQL = `([\s\S]*?)`;/);
if (!m) throw new Error("SCHEMA_SQL not found in src/db/sql.ts");
const out = new URL("../supabase/migrations/20261029000000_back_office.sql", import.meta.url);
const body = `-- Generated by scripts/db-sql.mjs from src/db/sql.ts. Do not edit by hand.\n${m[1].trimStart()}`;

if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (cur !== body) {
    console.error("supabase migration is out of date: run node scripts/db-sql.mjs");
    process.exit(1);
  }
  console.log("migration matches src/db/sql.ts");
} else {
  mkdirSync(new URL("../supabase/migrations/", import.meta.url), { recursive: true });
  writeFileSync(out, body);
  console.log("wrote", out.pathname);
}
