// Build src/lib/worldmap.ts: a dotted world map from the Americas to Japan
// and Australia, for the Rockmotion shipping routes. Land from Natural Earth
// (public domain) via world-atlas.
//
//   node scripts/world-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-50m.json", import.meta.url)));
const land = feature(topo, topo.objects.land);

// keep in step with project() in src/lib/rockmotion.ts
const BOX = { west: -130, east: 160, south: -48, north: 62 };
const K = Math.cos((22 * Math.PI) / 180);
const W = 1000;
const H = Math.round((W * (BOX.north - BOX.south)) / ((BOX.east - BOX.west) * K));
const STEP = 1.7;

const x = (lon) => ((lon - BOX.west) / (BOX.east - BOX.west)) * W;
const y = (lat) => ((BOX.north - lat) / (BOX.north - BOX.south)) * H;

let d = "";
let n = 0;
for (let lat = BOX.north - STEP / 2; lat > BOX.south; lat -= STEP)
  for (let lon = BOX.west + STEP / 2; lon < BOX.east; lon += STEP)
    if (geoContains(land, [lon, lat])) {
      d += `M${x(lon).toFixed(1)} ${y(lat).toFixed(1)}h0`;
      n++;
    }

writeFileSync(
  new URL("../src/lib/worldmap.ts", import.meta.url),
  `// Generated by scripts/world-dots.mjs from Natural Earth land (public domain). Do not edit.\n` +
    `export const WORLD = { box: ${JSON.stringify(BOX)}, k: ${K.toFixed(5)}, w: ${W}, h: ${H}, step: ${STEP} } as const;\n` +
    `export const LAND_DOTS = "${d}";\n`,
);
console.log(n, "dots", (d.length / 1024).toFixed(1), "KB", W, "x", H);
