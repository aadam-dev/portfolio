import { useEffect, useMemo, useRef, useState, type MutableRefObject, type ReactNode, type RefObject } from "react";
import { Canvas, useFrame, useThree, type ThreeEvent } from "@react-three/fiber";
import { Html, useTexture } from "@react-three/drei";
import { NextIntlClientProvider, useLocale, useMessages, useTimeZone, type AbstractIntlMessages } from "next-intl";
import { osText } from "@/components/os/l10n";
import * as THREE from "three";
import sceneData from "../../../public/workspace/scene.json";

/*
 * The photographed desk as real 3D. Simple shapes stand where the photo's objects are (generated by
 * scripts/desk-photo/proxies.py from the camera solved from the photo), and each one is painted by
 * projecting the photo from that same camera. From the home pose it is the photo, pixel for pixel;
 * as the camera moves the shapes give it depth, the screens run live apps, and the lamp, phone,
 * mouse and ball can be used.
 */

type V3 = [number, number, number];
interface Proxy {
  id: string;
  kind: "quad" | "box" | "cyl" | "sphere" | "ellipsoid";
  corners?: V3[];
  center?: V3;
  size?: V3;
  rotY?: number;
  r?: number;
  r2?: number;
  h?: number;
  radius?: number;
  radii?: V3;
  moving?: boolean;
  hotspot?: string;
}
interface SceneData {
  camera: { position: V3; target: V3; fov: number; aspect: number };
  proxies: Proxy[];
  screens: Record<"left" | "center" | "right", V3[]>;
  stops: Record<string, { look: V3; dist: number | null }>;
  lamp: { bulb: V3 };
}
const S = sceneData as unknown as SceneData;
const v = (p: number[]) => new THREE.Vector3(p[0], p[1], p[2]);
const clamp = (x: number, a = 0, b = 1) => Math.min(b, Math.max(a, x));
const ease = (t: number) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);

export type ScreenId = "left" | "center" | "right";
export interface DeskRig {
  /** scroll progress through the tour, 0..1 (LAND and beyond = in the laptop) */
  p: number;
  /** pointer in -1..1, for a little parallax at home */
  px: number;
  py: number;
}

/* ------------------------------------------------------------------ the photo's camera */

const PHOTO_CAM = (() => {
  const c = new THREE.PerspectiveCamera(S.camera.fov, S.camera.aspect, 0.01, 50);
  c.position.copy(v(S.camera.position));
  c.lookAt(v(S.camera.target));
  c.updateMatrixWorld(true);
  c.updateProjectionMatrix();
  return c;
})();
const PHOTO_VP = new THREE.Matrix4().multiplyMatrices(PHOTO_CAM.projectionMatrix, PHOTO_CAM.matrixWorldInverse);
const HOME_POS = v(S.camera.position);
const HOME_LOOK = v(S.camera.target);
const PHOTO_HFOV = 2 * Math.atan(Math.tan(THREE.MathUtils.degToRad(S.camera.fov / 2)) * S.camera.aspect);

/** Vertical fov that frames the photo like object-fit: cover at this viewport aspect. */
function coverFov(aspect: number) {
  if (aspect < S.camera.aspect) return S.camera.fov;
  return THREE.MathUtils.radToDeg(2 * Math.atan(Math.tan(PHOTO_HFOV / 2) / aspect));
}

/* ------------------------------------------------------------------ the projected-photo shader */

const VERT = /* glsl */ `
uniform mat4 photoVP;
uniform mat4 rest;      // for moving things: their world matrix at rest, so the picture travels with them
uniform float moving;
varying vec4 vPhoto;
varying vec3 vWorld;
void main() {
  vec4 wp = modelMatrix * vec4(position, 1.0);
  vec4 rp = moving > 0.5 ? rest * vec4(position, 1.0) : wp;
  vPhoto = photoVP * rp;
  vWorld = wp.xyz;
  gl_Position = projectionMatrix * viewMatrix * wp;
}`;

const FRAG = /* glsl */ `
uniform sampler2D photo;
uniform float night;
uniform float hover;
uniform vec3 bulb;
uniform vec3 screenC;
varying vec4 vPhoto;
varying vec3 vWorld;
void main() {
  vec2 uv = clamp(vPhoto.xy / vPhoto.w * 0.5 + 0.5, 0.001, 0.999);
  vec3 c = texture2D(photo, uv).rgb;
  // night: the room goes blue-dark, the lamp throws a warm pool, the screens a cool glow
  float dl = distance(vWorld, bulb);
  vec3 lampLight = vec3(1.0, 0.62, 0.32) * 0.95 / (1.0 + 9.0 * dl * dl);
  float ds = distance(vWorld, screenC);
  vec3 screenLight = vec3(0.45, 0.55, 0.9) * 0.22 / (1.0 + 14.0 * ds * ds);
  vec3 dark = c * vec3(0.1, 0.11, 0.18);
  vec3 lit = dark + c * (lampLight + screenLight) * 2.0;
  c = mix(c, lit, night);
  c += hover * 0.07;
  gl_FragColor = vec4(c, 1.0);
  #include <colorspace_fragment>
}`;

function photoMaterial(tex: THREE.Texture, rest?: THREE.Matrix4) {
  return new THREE.ShaderMaterial({
    vertexShader: VERT,
    fragmentShader: FRAG,
    uniforms: {
      photo: { value: tex },
      photoVP: { value: PHOTO_VP },
      rest: { value: rest ?? new THREE.Matrix4() },
      moving: { value: rest ? 1 : 0 },
      night: { value: 0 },
      hover: { value: 0 },
      bulb: { value: v(S.lamp.bulb) },
      screenC: { value: v(S.screens.center[0]).add(v(S.screens.center[2])).multiplyScalar(0.5) },
    },
  });
}

/* ------------------------------------------------------------------ geometry */

function geometryOf(p: Proxy): THREE.BufferGeometry {
  if (p.kind === "quad") {
    const [a, b, c, d] = p.corners!.map(v);
    const g = new THREE.BufferGeometry();
    g.setFromPoints([a, d, b, b, d, c]);
    g.computeVertexNormals();
    return g;
  }
  if (p.kind === "box") return new THREE.BoxGeometry(p.size![0], p.size![1], p.size![2]);
  if (p.kind === "cyl") return new THREE.CylinderGeometry(p.r!, p.r2 ?? p.r!, p.h!, 48);
  if (p.kind === "sphere") return new THREE.SphereGeometry(p.radius!, 48, 32);
  const g = new THREE.SphereGeometry(1, 40, 24);
  g.scale(...(p.radii as V3));
  return g;
}

/** A screen's frame from its corners (TL, TR, BR, BL): centre, axes, size. */
function frameOf(q: V3[]) {
  const [tl, tr, , bl] = q.map(v);
  const x = tr.clone().sub(tl);
  const y = tl.clone().sub(bl);
  const w = x.length();
  const h = y.length();
  x.normalize();
  y.normalize();
  const z = new THREE.Vector3().crossVectors(x, y).normalize();
  const c = q.map(v).reduce((a, b) => a.add(b), new THREE.Vector3()).multiplyScalar(0.25);
  const quat = new THREE.Quaternion().setFromRotationMatrix(new THREE.Matrix4().makeBasis(x, y, z));
  return { c, z, w, h, quat };
}
export const FRAMES = { left: frameOf(S.screens.left), center: frameOf(S.screens.center), right: frameOf(S.screens.right) };
export const SCREEN_PX: Record<ScreenId, [number, number]> = { left: [1200, 780], center: [1600, 1000], right: [1200, 780] };

// drei's Html rebuilds its React root when these props change identity, so they are constants
const Z_SCREENS: [number, number] = [3, 0];
const Z_LABEL: [number, number] = [20, 10];
const LABEL_STYLE = { pointerEvents: "none" } as const;
const OFFSTAGE: V3 = [0, -5, 0];
const SCREEN_STYLE: Record<ScreenId, { width: number; height: number }> = {
  left: { width: SCREEN_PX.left[0], height: SCREEN_PX.left[1] },
  center: { width: SCREEN_PX.center[0], height: SCREEN_PX.center[1] },
  right: { width: SCREEN_PX.right[0], height: SCREEN_PX.right[1] },
};

/* ------------------------------------------------------------------ camera rig */

interface Pose {
  pos: THREE.Vector3;
  look: THREE.Vector3;
}

/** Each chapter's camera: dolly toward the object along the photo camera's line of sight, object to one side. */
function stopPose(id: string, side: "left" | "right", fov: number, aspect: number, landing: number): Pose {
  if (id === "screens") {
    const f = FRAMES.center;
    const t = Math.tan(THREE.MathUtils.degToRad(fov / 2));
    // fill the viewport with the laptop screen, a touch past its edges
    const d = Math.min(f.h / 2 / t, f.w / 2 / (t * aspect)) * landing;
    return { pos: f.c.clone().addScaledVector(f.z, d), look: f.c.clone() };
  }
  const st = S.stops[id];
  if (!st || st.dist == null) return { pos: HOME_POS.clone(), look: HOME_LOOK.clone() };
  const L = v(st.look);
  const dir = HOME_POS.clone().sub(L).normalize();
  const pos = L.clone().addScaledVector(dir, st.dist);
  // put the object on the side away from the copy card
  const right = new THREE.Vector3().crossVectors(dir.clone().negate(), new THREE.Vector3(0, 1, 0)).normalize();
  const halfW = st.dist * Math.tan(THREE.MathUtils.degToRad(fov / 2)) * aspect;
  const shift = (side === "left" ? -1 : 1) * 0.36 * halfW;
  return { pos: pos.addScaledVector(right, shift), look: L.clone().addScaledVector(right, shift) };
}

/* ------------------------------------------------------------------ per-frame writes */

function aim(cam: THREE.PerspectiveCamera, pos: THREE.Vector3, look: THREE.Vector3, fov: number) {
  cam.fov = fov;
  cam.near = 0.01;
  cam.far = 40;
  cam.position.copy(pos);
  cam.lookAt(look);
  cam.updateProjectionMatrix();
}

function paintSpot(el: HTMLDivElement, x: number, y: number, opacity: number) {
  if (opacity > 0) el.style.background = `radial-gradient(circle at ${x}px ${y}px, transparent 0, transparent 14vmin, rgba(10,8,6,0.62) 42vmin)`;
  el.style.opacity = String(opacity);
}

function shade(items: { p: Proxy; mat: THREE.ShaderMaterial }[], night: number, hover: string | null, dt: number) {
  for (const it of items) {
    it.mat.uniforms.night.value = night;
    const target = hover && it.p.hotspot === hover ? 1 : 0;
    it.mat.uniforms.hover.value += (target - it.mat.uniforms.hover.value) * (1 - Math.exp(-dt * 10));
  }
}

/* ------------------------------------------------------------------ scene */

interface SceneProps {
  rig: MutableRefObject<DeskRig>;
  stops: { id: string; side: "left" | "right" }[];
  land: number;
  landed: boolean;
  night: boolean;
  screens: Record<ScreenId, ReactNode>;
  spot: MutableRefObject<HTMLDivElement | null>;
  onPick: (stopIndex: number) => void;
  onLamp: (e: { x: number; y: number }) => void;
  onPhone: () => void;
  onReady: () => void;
  /** a fixed element for the live screens to mount in (stops them remounting when R3F's events connect) */
  portal: MutableRefObject<HTMLDivElement | null>;
  /** drei's Html renders in its own React root, so the language is handed in and provided again there */
  intl: { locale: string; messages: AbstractIntlMessages; timeZone?: string };
  labels: Record<string, string>;
}


function Scene({ rig, stops, land, landed, night, screens, spot, onPick, onLamp, onPhone, onReady, portal, intl, labels }: SceneProps) {
  const [clean, original] = useTexture(["/workspace/wide-clean.webp", "/workspace/wide.webp"]);
  const { size } = useThree();
  const [hover, setHover] = useState<string | null>(null);

  useMemo(() => {
    for (const t of [clean, original]) {
      t.colorSpace = THREE.SRGBColorSpace;
      t.anisotropy = 8;
      t.generateMipmaps = true;
    }
  }, [clean, original]);

  // one material per shape, so hover can light one object; moving shapes keep their rest projection
  const items = useMemo(
    () =>
      S.proxies.map((p) => {
        const geo = geometryOf(p);
        const pos = p.kind === "quad" ? new THREE.Vector3() : v(p.center!);
        const rot = new THREE.Euler(0, p.rotY ?? 0, 0);
        const rest = p.moving ? new THREE.Matrix4().compose(pos, new THREE.Quaternion().setFromEuler(rot), new THREE.Vector3(1, 1, 1)) : undefined;
        return { p, geo, pos, rot, mat: photoMaterial(p.moving ? original : clean, rest) };
      }),
    [clean, original],
  );
  const ball = useRef<THREE.Mesh>(null);
  const mouse = useRef<THREE.Mesh>(null);
  const motion = useRef({ ballY: 0, ballV: 0, nightT: 0 });
  const drag = useRef<{ moved: number; last: THREE.Vector3 } | null>(null);
  const cursor = useRef<HTMLDivElement>(null);
  const osEl = useRef<HTMLDivElement>(null);

  useEffect(() => {
    onReady();
  }, [onReady]);

  const tmpA = useMemo(() => ({ pos: new THREE.Vector3(), look: new THREE.Vector3() }), []);

  useFrame((state, dtRaw) => {
    const dt = Math.min(dtRaw, 1 / 20);
    const cam = state.camera as THREE.PerspectiveCamera;
    const aspect = size.width / size.height;
    const fov = coverFov(aspect);
    const N = stops.length;
    const { p, px, py } = rig.current;
    const raw = clamp(p / land) * (N - 1);
    const i = Math.min(N - 2, Math.floor(raw));
    const f = raw - i;
    const travel = ease(clamp((f - 0.42) / 0.58));
    const done = p >= land;
    const A = stopPose(stops[i].id, stops[i].side, fov, aspect, 0.98);
    const B = stopPose(stops[i + 1].id, stops[i + 1].side, fov, aspect, 0.98);
    const pose = done ? stopPose("screens", "left", fov, aspect, 0.98) : { pos: A.pos.lerp(B.pos, travel), look: A.look.lerp(B.look, travel) };
    // at home, a little parallax with the pointer shows the depth
    const home = 1 - clamp(raw * 3);
    pose.pos.x += px * 0.03 * home;
    pose.pos.y += py * 0.015 * home;
    tmpA.pos.lerp(pose.pos, tmpA.pos.lengthSq() === 0 ? 1 : 1 - Math.exp(-dt * 12));
    tmpA.look.lerp(pose.look, tmpA.look.lengthSq() === 0 ? 1 : 1 - Math.exp(-dt * 12));
    aim(cam, tmpA.pos, tmpA.look, fov);

    // spotlight on the object we're travelling to
    if (spot.current) {
      const tgt = stops[i + 1];
      const st = S.stops[tgt.id];
      if (!done && st && st.dist != null) {
        const q = v(st.look).project(cam);
        const sx = (q.x * 0.5 + 0.5) * size.width;
        const sy = (-q.y * 0.5 + 0.5) * size.height;
        paintSpot(spot.current, sx, sy, Math.sin(travel * Math.PI) * 0.9);
      } else paintSpot(spot.current, 0, 0, 0);
    }

    // night eases in and out
    const m = motion.current;
    m.nightT += ((night ? 1 : 0) - m.nightT) * (1 - Math.exp(-dt * 3));
    // the ball: a bounce with a little loss each time
    if (m.ballV !== 0 || m.ballY > 0) {
      m.ballV -= 9.8 * dt;
      m.ballY += m.ballV * dt;
      if (m.ballY <= 0) {
        m.ballY = 0;
        m.ballV = Math.abs(m.ballV) > 0.5 ? -m.ballV * 0.6 : 0;
      }
    }
    if (ball.current) ball.current.position.y = items.find((x) => x.p.id === "ball")!.pos.y + m.ballY;
    shade(items, m.nightT, hover, dt);
  });

  // the mouse slides on the mat; the cursor on the laptop follows it
  // the free part of the mat, right of the keyboard
  const matP = S.proxies.find((p) => p.id === "mat")!;
  const kbP = S.proxies.find((p) => p.id === "keyboard")!;
  const x0 = kbP.center![0] + kbP.size![0] / 2 + 0.035;
  const x1 = matP.center![0] + matP.size![0] / 2 - 0.035;
  const matC = new THREE.Vector3((x0 + x1) / 2, 0, matP.center![2]);
  const half = { x: (x1 - x0) / 2, z: matP.size![2] / 2 - 0.04 };
  const mouseRest = v(S.proxies.find((p) => p.id === "mouse")!.center!);
  const plane = useMemo(() => new THREE.Plane(new THREE.Vector3(0, 1, 0), -mouseRest.y), [mouseRest.y]);
  const placeCursor = (x: number, z: number) => {
    const u = clamp((x - (matC.x - half.x)) / (2 * half.x));
    const w = clamp((z - (matC.z - half.z)) / (2 * half.z));
    const [W, H] = SCREEN_PX.center;
    if (cursor.current) cursor.current.style.transform = `translate(${(u * W).toFixed(1)}px, ${(w * H).toFixed(1)}px)`;
  };
  const clickAtCursor = () => {
    const c = cursor.current;
    const root = osEl.current;
    if (!c || !root) return;
    const r = c.getBoundingClientRect();
    // the projected OS ignores the pointer; let it answer this one click
    const prev = root.style.pointerEvents;
    root.querySelectorAll<HTMLElement>("*").forEach((el) => (el.style.pointerEvents = "auto"));
    c.style.visibility = "hidden";
    const hit = document.elementFromPoint(r.left + 2, r.top + 2) as HTMLElement | null;
    c.style.visibility = "";
    root.querySelectorAll<HTMLElement>("*").forEach((el) => (el.style.pointerEvents = ""));
    root.style.pointerEvents = prev;
    if (hit && root.contains(hit)) hit.click();
  };

  const down = (id: string) => (e: ThreeEvent<PointerEvent>) => {
    if (landed) return;
    e.stopPropagation();
    if (id === "mouse") {
      (e.target as unknown as Element)?.setPointerCapture?.(e.pointerId);
      drag.current = { moved: 0, last: new THREE.Vector3() };
    }
  };
  const move = (e: ThreeEvent<PointerEvent>) => {
    const g = drag.current;
    if (!g || !mouse.current) return;
    const p = new THREE.Vector3();
    if (!e.ray.intersectPlane(plane, p)) return;
    const x = clamp(p.x, matC.x - half.x, matC.x + half.x);
    const z = clamp(p.z, matC.z - half.z, matC.z + half.z);
    if (g.last.lengthSq()) g.moved += g.last.distanceTo(p);
    g.last.copy(p);
    mouse.current.position.set(x, mouseRest.y, z);
    placeCursor(x, z);
  };
  const up = (id: string) => (e: ThreeEvent<PointerEvent>) => {
    if (id !== "mouse") return;
    const g = drag.current;
    drag.current = null;
    e.stopPropagation();
    if (g && g.moved < 0.004) clickAtCursor();
  };
  const click = (p: Proxy) => (e: ThreeEvent<MouseEvent>) => {
    if (landed || !p.hotspot || p.hotspot === "mouse") return;
    e.stopPropagation();
    if (p.hotspot === "lamp") onLamp({ x: e.nativeEvent.clientX, y: e.nativeEvent.clientY });
    else if (p.hotspot === "phone") onPhone();
    else if (p.hotspot === "ball") motion.current.ballV = 2.4;
    else {
      const k = stops.findIndex((s) => s.id === p.hotspot);
      if (k >= 0) onPick(k);
    }
  };

  const labelAt = hover ? items.find((x) => x.p.hotspot === hover) : null;
  const labelPos = useMemo<V3>(() => {
    if (!labelAt) return OFFSTAGE;
    const q = labelAt.p.kind === "quad" ? labelCenter(labelAt.p) : labelAt.pos.clone().add(new THREE.Vector3(0, 0.08, 0));
    return [q.x, q.y, q.z];
  }, [labelAt]);

  return (
    <>
      {items.map((it) => (
        <mesh
          key={it.p.id}
          ref={it.p.id === "ball" ? ball : it.p.id === "mouse" ? mouse : undefined}
          geometry={it.geo}
          material={it.mat}
          position={it.pos}
          rotation={it.rot}
          onPointerOver={
            it.p.hotspot && !landed
              ? (e) => {
                  e.stopPropagation();
                  setHover(it.p.hotspot!);
                  document.body.style.cursor = it.p.hotspot === "mouse" ? "grab" : "pointer";
                }
              : undefined
          }
          onPointerOut={it.p.hotspot ? () => ((document.body.style.cursor = ""), setHover(null)) : undefined}
          onPointerDown={it.p.hotspot ? down(it.p.hotspot) : undefined}
          onPointerMove={it.p.id === "mouse" ? move : undefined}
          onPointerUp={it.p.id === "mouse" ? up("mouse") : undefined}
          onClick={it.p.hotspot ? click(it.p) : undefined}
        />
      ))}

      {/* the three screens run real things */}
      {(Object.keys(FRAMES) as ScreenId[]).map((id) => {
        const f = FRAMES[id];
        const [W, H] = SCREEN_PX[id];
        // stays mounted when the OS goes full screen (unmounting an Html root mid-render upsets React 19)
        return (
          <group key={id} position={f.c} quaternion={f.quat} visible={!(id === "center" && landed)}>
            <Html transform portal={portal as RefObject<HTMLElement>} distanceFactor={(400 * f.w) / W} zIndexRange={Z_SCREENS} style={SCREEN_STYLE[id]} pointerEvents="none">
              <div ref={id === "center" ? osEl : undefined} className="theme-fixed relative overflow-hidden bg-black" style={{ width: W, height: H, visibility: id === "center" && landed ? "hidden" : undefined }}>
                <NextIntlClientProvider locale={intl.locale} messages={intl.messages} timeZone={intl.timeZone}>
                  {screens[id]}
                </NextIntlClientProvider>
                {id === "center" && (
                  <div ref={cursor} aria-hidden className="pointer-events-none absolute left-0 top-0 z-[600]" style={{ transform: `translate(${W * 0.62}px, ${H * 0.55}px)` }}>
                    <svg width="26" height="36" viewBox="0 0 16 22">
                      <path d="M1 1 L1 17 L5 13 L8 20 L11 19 L8 12 L14 12 Z" fill="#111" stroke="#fff" strokeWidth="1.4" />
                    </svg>
                  </div>
                )}
              </div>
            </Html>
          </group>
        );
      })}

      {/* one label, always mounted, moved to whatever is under the pointer */}
      <Html position={labelPos} portal={portal as RefObject<HTMLElement>} center zIndexRange={Z_LABEL} style={LABEL_STYLE}>
        <span className="theme-fixed whitespace-nowrap rounded-full bg-black/80 px-3 py-1 font-mono text-[10.5px] uppercase tracking-[0.14em] text-white transition-opacity" style={{ opacity: labelAt ? 1 : 0 }}>
          {labelAt ? labels[labelAt.p.hotspot!] ?? labelAt.p.id : ""}
        </span>
      </Html>
    </>
  );
}

function labelCenter(p: Proxy) {
  const c = p.corners!.map(v).reduce((a, b) => a.add(b), new THREE.Vector3()).multiplyScalar(0.25);
  return c.add(new THREE.Vector3(0, 0.06, 0.02));
}

/* ------------------------------------------------------------------ canvas */

export default function PhotoDesk(props: Omit<SceneProps, "onReady" | "portal" | "intl" | "labels"> & { active: boolean }) {
  const [ready, setReady] = useState(false);
  const locale = useLocale();
  const messages = useMessages();
  const timeZone = useTimeZone();
  const intl = useMemo(() => ({ locale, messages, timeZone }), [locale, messages, timeZone]);
  const labels = osText(locale).deskLabels;
  const { active, ...scene } = props;
  const portal = useRef<HTMLDivElement>(null);
  return (
    <div ref={portal} className="absolute inset-0 transition-opacity duration-500" style={{ opacity: ready ? 1 : 0 }}>
      <Canvas
        frameloop={active ? "always" : "never"}
        dpr={[1, 1.75]}
        gl={{ antialias: true, powerPreference: "high-performance" }}
        camera={{ fov: S.camera.fov, near: 0.01, far: 40, position: S.camera.position }}
        flat
        onCreated={({ gl }) => {
          gl.toneMapping = THREE.NoToneMapping;
        }}
      >
        <Scene {...scene} portal={portal} intl={intl} labels={labels} onReady={() => setReady(true)} />
      </Canvas>
    </div>
  );
}

