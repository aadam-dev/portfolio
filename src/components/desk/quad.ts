/** Screen corners as fractions of the photo: TL, TR, BR, BL. */
export type Quad = [[number, number], [number, number], [number, number], [number, number]];

/** Solve the 8 projective coefficients mapping rect (0,0,w,h) onto dst (TL, TR, BR, BL). */
function solve(w: number, h: number, dst: [number, number][]) {
  const src: [number, number][] = [
    [0, 0],
    [w, 0],
    [w, h],
    [0, h],
  ];
  const A: number[][] = [];
  const b: number[] = [];
  for (let i = 0; i < 4; i++) {
    const [x, y] = src[i];
    const [u, v] = dst[i];
    A.push([x, y, 1, 0, 0, 0, -u * x, -u * y]);
    b.push(u);
    A.push([0, 0, 0, x, y, 1, -v * x, -v * y]);
    b.push(v);
  }
  for (let c = 0; c < 8; c++) {
    let p = c;
    for (let r = c + 1; r < 8; r++) if (Math.abs(A[r][c]) > Math.abs(A[p][c])) p = r;
    [A[c], A[p]] = [A[p], A[c]];
    [b[c], b[p]] = [b[p], b[c]];
    for (let r = 0; r < 8; r++) {
      if (r === c) continue;
      const f = A[r][c] / A[c][c];
      for (let k = c; k < 8; k++) A[r][k] -= f * A[c][k];
      b[r] -= f * b[c];
    }
  }
  return b.map((v, i) => v / A[i][i]);
}

/** CSS matrix3d that projects a w×h element (origin top-left) onto the quad. */
export function quadMatrix(w: number, h: number, dst: [number, number][]) {
  const [a, bb, c, d, e, f, g, hh] = solve(w, h, dst);
  return `matrix3d(${a},${d},0,${g},${bb},${e},0,${hh},0,0,1,0,${c},${f},0,1)`;
}
